"""报文装载 → 固件门禁 → 入栏/坏点/固件旁路归档。

固件门禁工程形态见 `app/services/固件白名单.py`：
- 低版本报文只进 `固件归档`（只读），现行 `入栏缓冲` 只收达标固件集；
- 入栏行带白名单指纹，低版本灌入后现行是否增行可区分；
- 批装载读白名单快照，落库前重读（并发检查点 `_钩子`），指纹变动则整批重评。
"""
from __future__ import annotations
import json
import sqlite3
import time
import uuid
from app.db import 连接
from app.seed import 此刻
from app.services import 校验, 目录, 时间, 固件白名单

_重评上限 = 6


def _批次号(体: dict) -> str:
    前 = str(体.get("批次编号") or "探批").strip() or "探批"
    return f"{前}-{uuid.uuid4().hex[:8]}"


def _处理(conn, 体: dict, 批次: str, 规: dict, 栏号: str, 站集合: set, 登记: dict,
          规则: dict, 仓时: str) -> dict:
    报文 = (体 or {}).get("报文") or []
    报告 = {
        "批次编号": 批次,
        "入流": 0,
        "入栏": 0,
        "坏点": 0,
        "驳回": 0,
        "固件拦截": 0,
        "归档": 0,
        "固件重评": 0,
        "规则指纹": 规则["指纹"],
        "最低固件版本": 规则["最低版本"],
        "明细": [],
    }
    for ev in 报文:
        行错 = 校验.校验报文(ev)
        if 行错:
            报告["驳回"] += 1
            报告["明细"].append({"命运": "驳回-校验", "说明": 校验.摘要错误(行错)})
            continue
        try:
            时间.解析时(ev["观测时"])
        except Exception:
            报告["驳回"] += 1
            报告["明细"].append({"命运": "驳回-观测时", "说明": ev.get("观测时")})
            continue
        编号 = ev["报文编号"]
        if conn.execute("SELECT 1 FROM 观测报文 WHERE 报文编号=?", (编号,)).fetchone():
            报告["驳回"] += 1
            报告["明细"].append({"命运": "驳回-幂等", "说明": 编号})
            continue
        if ev["站点键"] not in 站集合:
            报告["驳回"] += 1
            报告["明细"].append({"命运": "驳回-未知站点", "说明": ev["站点键"]})
            continue
        固件 = 固件白名单.有效固件(ev.get("固件版本"), ev["站点键"], 登记)
        状态, 原因 = 固件白名单.判定(固件, 规则["最低版本"])
        读数 = float(ev["读数"])
        处理 = 仓时
        漂 = 时间.漂移秒(ev["观测时"], 仓时)
        if 状态 == "低版本":
            报告["固件拦截"] += 1
            报告["归档"] += 1
            conn.execute(
                """INSERT INTO 观测报文(报文编号,站点键,指标键,读数,观测时,处理时,命运,批次编号,固件版本)
                   VALUES (?,?,?,?,?,?,?,?,?)""",
                (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 处理,
                 "固件旁路", 批次, 固件),
            )
            conn.execute(
                """INSERT INTO 固件归档(报文编号,站点键,指标键,读数,观测时,固件版本,固件指纹,原因,入档时)
                   VALUES (?,?,?,?,?,?,?,?,?)""",
                (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 固件,
                 规则["指纹"], 原因, 处理),
            )
            报告["明细"].append({
                "命运": "固件旁路",
                "报文编号": 编号,
                "固件版本": 固件,
                "原因": 原因,
                "归档": "只读归档",
            })
            continue
        conn.execute(
            """INSERT INTO 观测报文(报文编号,站点键,指标键,读数,观测时,处理时,命运,批次编号,固件版本)
               VALUES (?,?,?,?,?,?,?,?,?)""",
            (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 处理,
             "已装载", 批次, 固件),
        )
        报告["入流"] += 1
        ok, 门槛原因 = 校验.过门槛(读数, 规, ev["指标键"])
        if ok:
            conn.execute(
                """INSERT INTO 入栏缓冲(报文编号,站点键,指标键,读数,观测时,栏号,命运,入栏时,固件版本,固件指纹)
                   VALUES (?,?,?,?,?,?,?,?,?,?)""",
                (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 栏号, "在栏", 处理,
                 固件, 规则["指纹"]),
            )
            conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已入栏", 编号))
            报告["入栏"] += 1
            报告["明细"].append({
                "命运": "入栏",
                "报文编号": 编号,
                "栏号": 栏号,
                "漂移秒": 漂,
                "受控": 校验.指标是否受控(ev["指标键"]),
                "固件版本": 固件,
                "固件指纹": 规则["指纹"],
            })
        else:
            conn.execute(
                """INSERT INTO 坏点匣(报文编号,站点键,原因,读数,观测时,入匣时)
                   VALUES (?,?,?,?,?,?)""",
                (编号, ev["站点键"], 门槛原因, 读数, ev["观测时"], 处理),
            )
            conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已坏点", 编号))
            报告["坏点"] += 1
            报告["明细"].append({"命运": "坏点", "报文编号": 编号, "原因": 门槛原因})
    return 报告


def 装一批(体: dict) -> dict:
    体 = 体 or {}
    批次 = _批次号(体)
    预检 = 校验.校验批次(体)
    规 = 目录.栏规()
    栏号 = 规.get("当前栏号", "B-demo")
    站集合 = {s["源键"] for s in 目录.站点列表()}
    仓时 = 此刻()
    快照 = 固件白名单.当前规则()
    重评 = 0
    报告: dict | None = None
    for 尝试 in range(_重评上限):
        钩子 = getattr(固件白名单, "_钩子", None)
        if 钩子 is not None:
            钩子()
        conn = 连接()
        try:
            # BEGIN IMMEDIATE 抢写锁：白名单读、判定、落库同一事务，
            # 阻塞并发 `设最低版本`，切换瞬间不漏拦。
            conn.execute("BEGIN IMMEDIATE")
            规则 = 固件白名单.当前规则(conn, 提交=False)
            if 规则["指纹"] != 快照["指纹"]:
                重评 += 1
                快照 = 规则
            登记 = 固件白名单.登记探头表(conn)
            报告 = _处理(conn, 体, 批次, 规, 栏号, 站集合, 登记, 规则, 仓时)
            报告["固件重评"] = 重评
            if 预检:
                报告["明细"].insert(0, {"命运": "批次预检", "说明": 校验.摘要错误(预检)})
            if 固件白名单.当前规则(conn, 提交=False)["指纹"] != 规则["指纹"]:
                conn.rollback()
                continue
            conn.execute(
                """INSERT INTO 装载批次(编号,时刻,入流,入栏,坏点,报告) VALUES (?,?,?,?,?,?)""",
                (批次, 仓时, 报告["入流"], 报告["入栏"], 报告["坏点"],
                 json.dumps(报告, ensure_ascii=False)),
            )
            conn.commit()
            break
        except sqlite3.OperationalError:
            conn.rollback()
            if 尝试 + 1 >= _重评上限:
                raise
            time.sleep(0.02 * (尝试 + 1))
        finally:
            conn.close()
    else:
        报告 = 报告 or {"批次编号": 批次}
        报告["错误"] = "白名单频繁变动，批次未落库"
    return 报告
