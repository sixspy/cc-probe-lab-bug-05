"""失败测乙：站点源对账在固件灯红时仍把有入栏当合法绿则红。

约束：
- 站点源对账须读真实固件灯，灯红且有入栏不得报合法绿；
- 低版本被拦后进入只读归档，对账状态须能区分“红-无入栏”与“红-有入栏漏检”；
- 白名单指纹须留痕，且拒低版本回刷。
"""
from app.services import 装载, 目录, 固件白名单


def _体(编号: str, 站点: str, 固件: str | None = None, 读数: float = 20.0) -> dict:
    ev = {
        "报文编号": 编号,
        "站点键": 站点,
        "指标键": "PM25",
        "读数": 读数,
        "观测时": "2026-11-24T11:00:00Z",
    }
    if 固件 is not None:
        ev["固件版本"] = 固件
    return {"批次编号": "夹具-固件门禁乙", "报文": [ev]}


def test_登记低版本探头后站点源灯转红():
    固件白名单.登记探头("站-湖西", "1.0.0")
    账 = 固件白名单.对账()
    assert 账["灯"]["站-湖西"] == "红"
    assert 账["合法绿"] is False


def test_低版本被拦后对账为合法红而非绿():
    固件白名单.登记探头("站-湖西", "1.0.0")
    报告 = 装载.装一批(_体("FW-B-low", "站-湖西", 固件="1.0.0"))
    assert 报告["入栏"] == 0
    assert 报告["归档"] == 1
    账 = 固件白名单.对账()
    assert 账["现行入栏低版行"] == 0
    assert 账["有入栏"] is False
    assert 账["状态"] == "红-无入栏"
    assert 账["合法绿"] is False
    assert 账["归档笔数"] == 1


def test_灯红且有入栏不得报合法绿():
    # 模拟半修/旧轨漏入：灯红的同时现行入栏仍有低版本行
    固件白名单.登记探头("站-林场", "1.0.0")
    装载.装一批(_体("FW-B-pass", "站-林场", 固件="1.4.2"))
    conn = __import__("app.db", fromlist=["连接"]).连接()
    try:
        conn.execute(
            """INSERT INTO 入栏缓冲(报文编号,站点键,指标键,读数,观测时,栏号,命运,入栏时,固件版本,固件指纹)
               VALUES (?,?,?,?,?,?,?,?,?,?)""",
            ("FW-B-leak", "站-林场", "PM25", 21.0, "2026-11-24T11:10:00Z", "B-demo", "在栏",
             "2026-11-24T11:11:00Z", "1.0.0", 固件白名单.当前规则()["指纹"]),
        )
        conn.commit()
    finally:
        conn.close()
    账 = 固件白名单.对账()
    assert 账["灯"]["站-林场"] == "红"
    assert 账["有入栏"] is True
    assert 账["现行入栏低版行"] == 1
    assert 账["状态"] == "红-有入栏漏检"
    assert 账["合法绿"] is False, "灯红且有入栏仍报合法绿"


def test_全绿时对账才合法绿():
    装载.装一批(_体("FW-B-ok", "站-河东", 固件="1.4.2"))
    账 = 固件白名单.对账()
    assert 账["合法绿"] is True
    assert 账["状态"] == "绿"


def test_拒低版本回刷且指纹留痕():
    规则0 = 固件白名单.当前规则()
    out = 固件白名单.设最低版本("1.1.0", 备注="试图回刷")
    assert "错误" in out
    assert 固件白名单.当前规则()["指纹"] == 规则0["指纹"]
    ok = 固件白名单.设最低版本("1.3.0", 备注="抬升")
    assert "错误" not in ok
    规则1 = 固件白名单.当前规则()
    assert 规则1["指纹"] != 规则0["指纹"]
    assert 规则1["最低版本"] == "1.3.0"
    assert 规则1["史"], "白名单变更须留指纹史"
