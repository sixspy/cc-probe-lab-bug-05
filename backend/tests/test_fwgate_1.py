"""失败测甲：低版本装载后现行入栏行数仍升则红。

约束：
- 低版本固件须拒或旁路，不得进现行入栏缓冲；
- 低版本灌入后，现行是否增行须可区分（入栏不增、只读归档有据）；
- 站点源登记低版本探头后，未带固件版本的夹具也须按登记固件受门禁。
"""
from app.services import 装载, 目录, 固件白名单


def _体(编号: str, 固件: str | None = None, 站点: str = "站-河东", 读数: float = 20.0) -> dict:
    ev = {
        "报文编号": 编号,
        "站点键": 站点,
        "指标键": "PM25",
        "读数": 读数,
        "观测时": "2026-11-24T10:00:00Z",
    }
    if 固件 is not None:
        ev["固件版本"] = 固件
    return {"批次编号": "夹具-固件门禁甲", "报文": [ev]}


def test_报文级低版本不入栏只归档():
    before = len(目录.缓冲列表())
    报告 = 装载.装一批(_体("FW-A-low-msg", 固件="1.0.0"))
    assert 报告["入栏"] == 0, "低版本固件不得进入现行入栏"
    assert 报告.get("固件拦截", 0) == 1
    assert 报告.get("归档", 0) == 1
    after = len(目录.缓冲列表())
    assert after == before, "低版本装载后现行入栏行数仍升"
    assert any(
        r["报文编号"] == "FW-A-low-msg" for r in 目录.固件归档列表()
    ), "低版本须旁路进只读归档，增行去向须可区分"


def test_站点登记低版本探头后夹具也受门禁():
    固件白名单.登记探头("站-河东", "1.0.0")
    before = len(目录.缓冲列表())
    报告 = 装载.装一批(_体("FW-A-low-reg"))
    assert 报告["入栏"] == 0, "站点登记低版本探头后，未带固件版本的报文仍须拦"
    assert 报告.get("固件拦截", 0) == 1
    assert len(目录.缓冲列表()) == before, "低版本装载后现行入栏行数仍升"


def test_高版本固件仍可入栏():
    before = len(目录.缓冲列表())
    报告 = 装载.装一批(_体("FW-A-high", 固件="1.4.2"))
    assert 报告["入栏"] == 1
    assert 报告.get("固件拦截", 0) == 0
    assert len(目录.缓冲列表()) == before + 1
    rows = 目录.缓冲列表()
    row = next(r for r in rows if r["报文编号"] == "FW-A-high")
    assert row["固件版本"] == "1.4.2"
    assert row["固件指纹"], "入栏行须带白名单指纹，供对账与争用核验"
